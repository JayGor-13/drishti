"""Print every paper table (markdown) from the result files. No GPU, no network.

Usage:
  python scripts/make_tables.py --runs ../runs --trackers ../../antiuav410/scores --out ../runs/TABLES.md
(inside the handover package: python scripts/make_tables.py --runs runs --trackers antiuav410_scores --out TABLES.md)
"""
from __future__ import annotations

import argparse
import glob
import json
import os
import statistics as st
from pathlib import Path


def load(runs: Path, name: str) -> dict | None:
    d = runs / name
    for f in ("postprocess_sweep_low.json", "postprocess_sweep.json"):
        if (d / f).exists():
            s = json.load(open(d / f, encoding="utf-8"))["chosen_on_val"]
            row = {"track": s["test"]["antiuav_tracking_accuracy"], "map50": s["test"]["map50"], "map75": s["test"]["map75"],
                   "P": s["test"]["precision"], "R": s["test"]["recall"], "thr": s.get("threshold"), "file": f}
            c = d / "cost.json"
            if c.exists():
                cj = json.load(open(c, encoding="utf-8"))
                row.update({"gflops": cj.get("gflops"), "params": cj.get("params"), "ms": cj.get("latency_ms_batch1")})
            dec = d / "decode_raw.json"
            if dec.exists():
                dj = json.load(open(dec, encoding="utf-8"))
                row["dec0"] = dj.get("decoder_lag0", {}).get("test", {}).get("antiuav_tracking_accuracy")
                row["dec15"] = dj.get("decoder_lag15", {}).get("test", {}).get("antiuav_tracking_accuracy")
            return row
    return None


def pct(v, nd=1):
    return "-" if v is None else f"{100 * v:.{nd}f}"


def table(title, header, lines, out):
    out.append(f"\n### {title}\n")
    out.append("| " + " | ".join(header) + " |")
    out.append("|" + "---|" * len(header))
    out.extend("| " + " | ".join(str(c) for c in line) + " |" for line in lines)


def main() -> None:
    p = argparse.ArgumentParser(description="Paper tables from result files.")
    p.add_argument("--runs", default="../runs")
    p.add_argument("--trackers", default=None, help="folder with <tracker>_test.json score files")
    p.add_argument("--out", default=None)
    a = p.parse_args()
    runs = Path(a.runs)
    out: list[str] = ["# Tables (generated by scripts/make_tables.py; Anti-UAV410 test, val-chosen post-processing)"]

    def rows_for(spec, extra=()):
        lines = []
        for label, name in spec:
            r = load(runs, name)
            if r is None:
                lines.append([label, "-", "-", "-"] + ["-"] * len(extra)); continue
            line = [label, pct(r["track"], 2), pct(r["map50"]), pct(r["map75"])]
            for e in extra:
                if e == "GFLOPs": line.append("-" if not r.get("gflops") else f"{r['gflops']:.1f}")
                elif e == "+decoder": line.append(pct(r.get("dec15"), 2))
                elif e == "thr": line.append(str(r.get("thr")))
            lines.append(line)
        return lines

    # 1. main table: detectors
    main_spec = [("Ours: YOLO11n + compensated diffs (gaps 1, 12) + NWD, seed 42", "baseline_yolo11n_640_comp_k12_nwd"),
                 ("  seed 1", "baseline_yolo11n_640_comp_k12_nwd_s1"), ("  seed 2", "baseline_yolo11n_640_comp_k12_nwd_s2"),
                 ("Ours + P2 head (yolov8n-p2)", "baseline_yolov8n_p2_640_comp_k12_nwd"),
                 ("Ours recipe on YOLO26n", "baseline_yolo26n_640_comp_k12_nwd"),
                 ("YOLO11n gap 8 (seed 42)", "baseline_yolo11n_640_dyn_k8"),
                 ("YOLO11n, 2025 winner's input", "baseline_yolo11n_640_winner"),
                 ("YOLO11n plain (640)", "baseline_yolo11n_640"), ("YOLO11s plain (640)", "baseline_yolo11s_640"),
                 ("YOLO26n plain (640)", "baseline_yolo26n_640"),
                 ("YOLOv8n (512)", "baseline_yolov8n_512"), ("YOLOv9t (512)", "baseline_yolov9t_512"), ("YOLOv10n (512)", "baseline_yolov10n_512"),
                 ("YOLO11n (512)", "baseline_yolo11n_512"), ("YOLO12n (512)", "baseline_yolo12n_512"), ("YOLO26n (512)", "baseline_yolo26n_512"),
                 ("RT-DETR-l (512)", "baseline_rtdetr_l_512"), ("DINO-4scale R50", "baseline_dino_r50"), ("Deformable-DETR R50", "baseline_deformable_detr_r50"),
                 ("SSTNet (TGRS'24), their code", "baseline_sstnet"), ("CHAL (CVPR'26), their code", "baseline_chal")]
    table("Main table: detectors (no first-frame box)", ["Method", "Track acc.", "mAP50", "mAP75", "GFLOPs", "+decoder (lag 15)"],
          rows_for(main_spec, ("GFLOPs", "+decoder")), out)
    seeds = [load(runs, n) for n in ("baseline_yolo11n_640_comp_k12_nwd", "baseline_yolo11n_640_comp_k12_nwd_s1", "baseline_yolo11n_640_comp_k12_nwd_s2")]
    seeds = [100 * r["track"] for r in seeds if r]
    if len(seeds) > 1:
        out.append(f"\nOurs over {len(seeds)} seeds: {st.mean(seeds):.2f} +- {st.stdev(seeds):.2f}")

    # 2. trackers
    if a.trackers and Path(a.trackers).exists():
        lines = []
        for f in sorted(glob.glob(os.path.join(a.trackers, "*_test.json"))):
            s = json.load(open(f, encoding="utf-8")).get("summary", {})
            if "antiuav_tracking_accuracy" in s:
                lines.append([s.get("method", Path(f).stem), pct(s["antiuav_tracking_accuracy"], 2), pct(s.get("map50")), pct(s.get("map75"))])
        lines.sort(key=lambda l: -float(l[1]))
        table("Reference: published trackers (given the first-frame box; official raw results, our scorer)", ["Tracker", "Track acc.", "mAP50", "mAP75"], lines, out)

    # 3. build-up
    table("Build-up of the final system (YOLO11n-640)", ["Step", "Track acc.", "mAP50", "mAP75"], rows_for([
        ("plain frames", "baseline_yolo11n_640"), ("+ frame differences, gap 8", "baseline_yolo11n_640_dyn_k8"),
        ("+ gap 12", "baseline_yolo11n_640_dyn_k12"), ("+ ego-motion compensation (gap 8)", "baseline_yolo11n_640_dyn_k8_comp"),
        ("+ NWD loss (gap 8)", "baseline_yolo11n_640_dyn_k8_nwd"), ("compensation + gap 12", "baseline_yolo11n_640_comp_k12"),
        ("gap 12 + NWD", "baseline_yolo11n_640_k12_nwd"), ("plain + NWD", "baseline_yolo11n_640_plain_nwd"),
        ("FINAL: compensation + gap 12 + NWD", "baseline_yolo11n_640_comp_k12_nwd")]), out)

    # 4. motion-input ablation
    table("Motion input (YOLO11n-640)", ["Input", "Track acc.", "mAP50", "mAP75"], rows_for([
        ("plain", "baseline_yolo11n_640"), ("winner's: signed diffs t-1, t-2", "baseline_yolo11n_640_winner"),
        ("|diff| gaps 1, 3", "baseline_yolo11n_640_dyn"), ("gaps 1, 5", "baseline_yolo11n_640_dyn_k5"), ("gaps 1, 8", "baseline_yolo11n_640_dyn_k8"),
        ("gaps 1, 12", "baseline_yolo11n_640_dyn_k12"), ("gaps 1, 16", "baseline_yolo11n_640_dyn_k16"), ("gaps 3, 12 (no t-1)", "baseline_yolo11n_640_diff2_3_12"),
        ("+ optical flow", "baseline_yolo11n_640_flow"), ("time surface", "baseline_yolo11n_640_ts"), ("delta / delta-delta", "baseline_yolo11n_640_delta"),
        ("background subtraction", "baseline_yolo11n_640_bgmed"), ("compensated gaps 1, 8", "baseline_yolo11n_640_dyn_k8_comp"),
        ("compensated + temporal anomaly", "baseline_yolo11n_640_k8_comp_tprof"), ("compensated + local contrast", "baseline_yolo11n_640_k8_comp_lcm")]), out)

    # 5. other levers
    table("Other levers on gap 8 (none kept)", ["Lever", "Track acc.", "mAP50", "mAP75"], rows_for([
        ("every training frame", "baseline_yolo11n_640_dyn_k8_all"), ("input 800", "baseline_yolo11n_800_dyn_k8"), ("input 960", "baseline_yolo11n_960_dyn_k8"),
        ("test-time augmentation", "baseline_yolo11n_640_dyn_k8_tta"), ("motion-channel blanking", "baseline_yolo11n_640_dyn_k8_blank"),
        ("oversample crossover + clutter", "baseline_yolo11n_640_dyn_k8_over"), ("CLAHE", "baseline_yolo11n_640_dyn_k8_clahe"),
        ("box-loss weight x2", "baseline_yolo11n_640_box15"), ("rectangular training", "baseline_yolo11n_640_dyn_k8_rect"),
        ("box refiner", "baseline_yolo11n_640_dyn_refined"), ("zoom second look", "baseline_yolo11n_640_dyn_k8_zoom"),
        ("NWD c=0.5 / 1 / 2 (with compensation)", "baseline_yolo11n_640_comp_nwd_c05"), ("  c=1.0", "baseline_yolo11n_640_comp_nwd_full"),
        ("  c=2.0", "baseline_yolo11n_640_comp_nwd_c2")]), out)

    text = "\n".join(out) + "\n"
    if a.out:
        Path(a.out).write_text(text, encoding="utf-8")
        print(f"written {a.out}")
    print(text)


if __name__ == "__main__":
    main()
